"""Write ``docs/cli-reference.md`` from the ``jmap`` command tree.

Run it after you change a command::

    uv run python scripts/cli-reference.py

``--check`` writes nothing and exits 1 when the committed page is stale.
``tests/unit/test_docs.py`` makes the same check, so CI fails on a command
change that has no docs update.

The page lists every noun, verb, argument and option with its help, in
alphabetical order, so the output changes only when the commands do.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import TYPE_CHECKING, Any, Final, TypeAlias

import typer
import typer.core
import typer.main

from jmap.cli.app import app
from jmap.cli.commands import ALIASES

if TYPE_CHECKING:
    from collections.abc import Iterator, Sequence

Command: TypeAlias = typer.core.TyperCommand | typer.core.TyperGroup
Parameter: TypeAlias = typer.core.TyperOption | typer.core.TyperArgument

PAGE: Final = Path(__file__).resolve().parents[1] / "docs" / "cli-reference.md"

HEADER: Final = """\
# Command reference

<!-- Generated by scripts/cli-reference.py from the command tree. Do not edit. -->

Every `jmap` command, with its arguments and options, as its `--help` gives them.
[Command line](cli.md) explains how to use them. Commands are in alphabetical order.

After you change a command, run `uv run python scripts/cli-reference.py` to
update this page. A test fails while it is stale.
"""


def main(argv: Sequence[str]) -> int:
    text = render()
    if "--check" in argv:
        if PAGE.read_text(encoding="utf-8") == text:
            return 0
        sys.stderr.write(f"{PAGE} is stale: run uv run python scripts/cli-reference.py\n")
        return 1
    PAGE.write_text(text, encoding="utf-8")
    return 0


def render() -> str:
    """The whole page."""
    root = typer.main.get_command(app)
    assert isinstance(root, typer.core.TyperGroup)
    return Reference(root).markdown()


class Reference:
    """Renders the command tree under ``root`` as Markdown."""

    def __init__(self, root: typer.core.TyperGroup) -> None:
        self.root = root
        self.context = typer.Context(root, info_name="jmap")

    def markdown(self) -> str:
        lines = [HEADER, *self._globals(), *self._aliases()]
        for name, command, context in children(self.root, self.context):
            if name not in ALIASES:
                lines += self._command(["jmap", name], command, context, level=2)
        return "\n".join(lines).rstrip("\n") + "\n"

    def _globals(self) -> list[str]:
        return [
            "## Global options",
            "",
            "Each command takes these, before or after its own arguments.",
            "",
            *options_table(self.root.params),
            "",
        ]

    def _aliases(self) -> list[str]:
        lines = [
            "## Aliases",
            "",
            "The daily mail verbs also work without `mail`.",
            "",
            "| Command | Same as |",
            "|---|---|",
        ]
        for alias in sorted(ALIASES):
            target = f"jmap mail {ALIASES[alias]}"
            lines.append(f"| `jmap {alias}` | [`{target}`](#{anchor(target)}) |")
        return [*lines, ""]

    def _command(
        self, path: list[str], command: Command, context: typer.Context, level: int
    ) -> list[str]:
        lines = [f"{'#' * level} {' '.join(path)}", ""]
        if isinstance(command, typer.core.TyperCommand):
            lines += ["```text", usage(path, command.params), "```", ""]
        lines += [command.help or "", ""]
        arguments = [p for p in command.params if isinstance(p, typer.core.TyperArgument)]
        if arguments:
            lines += [*arguments_table(arguments), ""]
        if any(isinstance(p, typer.core.TyperOption) for p in command.params):
            lines += [*options_table(command.params), ""]
        if isinstance(command, typer.core.TyperGroup):
            for name, sub, sub_context in children(command, context):
                lines += self._command([*path, name], sub, sub_context, level + 1)
        return lines


def children(
    group: typer.core.TyperGroup, context: typer.Context
) -> Iterator[tuple[str, Command, typer.Context]]:
    """The visible subcommands of ``group``, by name."""
    for name in sorted(group.list_commands(context)):
        command = group.get_command(context, name)
        assert isinstance(command, typer.core.TyperCommand | typer.core.TyperGroup)
        if not command.hidden:
            yield name, command, typer.Context(command, info_name=name, parent=context)


def usage(path: list[str], params: list[Any]) -> str:
    words = [*path, "[OPTIONS]"]
    for param in params:
        if isinstance(param, typer.core.TyperArgument):
            words.append(argument_metavar(param))
    return " ".join(words)


def arguments_table(arguments: list[typer.core.TyperArgument]) -> list[str]:
    rows = ["| Argument | Description |", "|---|---|"]
    for argument in arguments:
        text = argument.help or ""
        if argument.required:
            text = f"{text} Required."
        elif argument.default not in (None, ()):
            text = f"{text} Default: `{argument.default}`."
        rows.append(f"| {cell(f'`{argument_metavar(argument)}`')} | {cell(text)} |")
    return rows


def options_table(params: list[Any]) -> list[str]:
    rows = ["| Option | Value | Description |", "|---|---|---|"]
    for option in params:
        if isinstance(option, typer.core.TyperOption) and not option.hidden:
            names = ", ".join(f"`{name}`" for name in option.opts)
            names += "".join(f" / `{name}`" for name in option.secondary_opts)
            value = option_metavar(option)
            text = (option.help or "") + option_default(option)
            value = cell(f"`{value}`") if value else ""
            rows.append(f"| {names} | {value} | {cell(text)} |")
    return rows


def argument_metavar(argument: typer.core.TyperArgument) -> str:
    name = (argument.metavar or argument.name or "").upper()
    if argument.nargs == -1:
        name += "..."
    # A metavar such as [KIND|OBJECT] already shows it is optional.
    return name if argument.required or name.startswith("[") else f"[{name}]"


def option_metavar(option: typer.core.TyperOption) -> str:
    """What follows the option on the line: nothing for a flag."""
    if option.is_flag or option.count:
        return ""
    if option.metavar:
        return option.metavar
    choices = getattr(option.type, "choices", None)
    if choices:
        return "|".join(str(choice) for choice in choices)
    return {"int": "N", "int range": "N", "path": "PATH"}.get(option.type.name, "TEXT")


def option_default(option: typer.core.TyperOption) -> str:
    default = option.default
    if option.secondary_opts and default is True:
        return f" Default: `{option.opts[-1]}`."
    if default is None or isinstance(default, bool) or default in ("", 0, ()) or option.count:
        return ""
    return f" Default: `{default}`."


def anchor(heading: str) -> str:
    """The id GitHub gives a heading."""
    return heading.lower().replace(" ", "-")


def cell(text: str) -> str:
    """Text that stays inside one table cell."""
    return " ".join(text.split()).replace("|", "\\|")


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
